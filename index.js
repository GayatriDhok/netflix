// Search functionality
function searchMovie() {
    const input = document.getElementById('searchInput').value.toLowerCase();
    const filteredMovies = allMovies.filter(movie => 
        movie.title.toLowerCase().includes(input)
    );
    displayMovies(filteredMovies);
}

// Filter functionality
function filterMovies(type) {
    currentFilter = type;
    
    // Update filter buttons
    document.querySelectorAll('.filter-btn').forEach(btn => {
        btn.classList.remove('active');
    });
    event.target.classList.add('active');
    
    let filteredMovies = allMovies;
    
    if (type !== 'all') {
        // Check if it's a popularity filter (High, Medium, Low)
        if (['High', 'Medium', 'Low'].includes(type)) {
            filteredMovies = allMovies.filter(movie => movie.popularityLevel === type);
        } 
        // Otherwise, treat it as genre filter
        else {
            filteredMovies = allMovies.filter(movie => 
                movie.genre.toLowerCase().includes(type.toLowerCase())
            );
        }
    }
    
    displayMovies(filteredMovies);
}

// Display movies
function displayMovies(moviesList) {
    const movieGrid = document.getElementById('movieGrid');
    movieGrid.innerHTML = '';
    
    moviesList.forEach(movie => {
        const movieCard = createMovieCard(movie);
        movieGrid.appendChild(movieCard);
    });
}

